#!/usr/bin/env python3
"""Validate executable, source-bound platform evidence from run-e2e.py.

Free-form agent-written PASS claims are deliberately rejected.
Log checksums and test-source fingerprints detect accidental stale evidence;
they are not a security boundary against an agent modifying the runner.
"""
import argparse
import datetime as dt
import hashlib
import json
from pathlib import Path
import sys
from importlib.machinery import SourceFileLoader


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def verify(report, profile, root, source_hash):
    issues = []
    if not isinstance(report, dict) or report.get("schema") != 2 or report.get("origin") != "harness-run-e2e":
        return ["report must be generated by run-e2e.py (schema 2), not handwritten"]
    if report.get("profile") != profile:
        issues.append("profile mismatch")
    if report.get("source_digest") != source_hash:
        issues.append("source files changed since E2E run; rerun")
    platforms = ("android", "ios") + (("web",) if profile == "mobile-web" else ())
    rows = report.get("results")
    if not isinstance(rows, dict):
        return ["results object missing"]
    for platform in platforms:
        row = rows.get(platform)
        if not isinstance(row, dict):
            issues.append(platform + ": MISSING test execution")
            continue
        expected_tool = "playwright-cli" if platform == "web" else "flutter-integration"
        if row.get("tool") != expected_tool:
            issues.append(platform + ": unsupported test tool")
        if not isinstance(row.get("target"), str) or not row["target"]:
            issues.append(platform + ": device / Web URL missing")
        status = row.get("status")
        code = row.get("exit_code")
        if status != "PASS" or code != 0:
            issues.append(platform + ": " + str(status) + " (exit=" + str(code) + ")")
        scenario = row.get("scenario")
        if not isinstance(scenario, str) or not scenario:
            issues.append(platform + ": scenario missing")
        else:
            path = (root / scenario).resolve()
            expected_dir = root / ("e2e" if platform == "web" else "integration_test")
            if not path.is_relative_to(expected_dir) or not path.is_file():
                issues.append(platform + ": scenario outside project or missing")
            elif sha256(path.read_bytes()) != row.get("scenario_sha256"):
                issues.append(platform + ": scenario modified since test")
        log_name = row.get("log")
        if not isinstance(log_name, str) or not log_name:
            issues.append(platform + ": evidence log missing")
        else:
            log = Path(log_name).resolve()
            if not log.is_file() or sha256(log.read_bytes()) != row.get("log_sha256"):
                issues.append(platform + ": evidence log missing or changed")
    return issues


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("--profile", choices=("mobile", "mobile-web"), default="mobile-web")
    args = parser.parse_args(argv)
    root = Path.cwd().resolve()
    try:
        report = json.loads(args.report.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print("INCOMPLETE E2E: " + str(exc))
        return 3
    runner = root / ".flutter-harness" / "bin" / "run-e2e.py"
    if not runner.is_file():
        print("INCOMPLETE E2E: run-e2e.py not installed")
        return 3
    loader = SourceFileLoader("harness_run_e2e", str(runner))
    source_hash = loader.load_module().source_digest(root)
    issues = verify(report, args.profile, root, source_hash)
    if issues:
        for issue in issues:
            print("INCOMPLETE E2E: " + issue)
        print("Keep PR Draft; fix scenario, rerun E2E, do not write PASS by hand")
        return 3
    print("PASS E2E: executed tests and source-bound logs for Android/iOS" +
          ("/Web" if args.profile == "mobile-web" else ""))
    print("NOTE: scenario assertion quality still needs independent review")
    return 0


if __name__ == "__main__":
    sys.exit(main())
